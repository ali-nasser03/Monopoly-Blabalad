package com.balbalad.monopoly.board;

/**
 * أنواع خانات اللوح، حسب القسم 5 من وثيقة المواصفات V1.
 */
public enum SquareType {
    GO,                 // البداية (خانة 0)
    PROPERTY,           // أرض قابلة للشراء والبناء عليها
    UTILITY,            // مرفق (كهرباء / مياه) - قابل للشراء، بدون بناء عليه
    CHANCE,             // فرصة
    COMMUNITY_CHEST,    // صندوق الجماعة
    JERUSALEM_GATE,     // بوابات القدس - غير قابلة للشراء، بطاقة عشوائية عند الوقوف عليها
    TAX,                // ضريبة تُدفع للبنك
    FREE_PARKING,       // المطل - استراحة مجانية، لا إجراء
    JAIL,               // المسكوبية - زيارة فقط أو سجن فعلي حسب حالة اللاعب
    GO_TO_JAIL          // استدعاء للمسكوبية - انتقال مباشر إلى المسكوبية كسجين
}
