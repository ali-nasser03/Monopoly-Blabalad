package com.balbalad.monopoly.game;

/** أنواع مفعول بطاقات فرصة/صندوق الجماعة/بوابات القدس. */
public enum CardEffectType {
    PAY,                // ادفع مبلغ ثابت للبنك
    COLLECT,            // اقبض مبلغ ثابت من البنك
    COLLECT_FROM_ALL,   // كل لاعب متصل تاني بيدفعلك مبلغ ثابت
    PAY_PER_BUILDING,   // ادفع حسب عدد الدور والعمارات يلي تملكها
    MOVE_TO,            // انتقل لخانة محددة (مع مكافأة المرور بالبداية لو انطبقت)
    MOVE_TO_BACKWARD,   // ارجع لخانة محددة بالاتجاه المعاكس (بدون قبض 200 أو لف اللوح للأمام)
    MOVE_RELATIVE,      // تقدم/ارجع عدد خطوات (سالب = للخلف)
    GO_TO_JAIL,         // انتقال مباشر للمسكوبية كسجين
    GATE_CLOSED,        // تخطي الدور الجاي (بس تحصيل الإيجارات عادي)
    DRAW_CHANCE,        // اسحب بطاقة فرصة (من بوابة بس)
    DRAW_CHEST,         // اسحب بطاقة صندوق جماعة (من بوابة بس)
    JAIL_FREE_CARD      // بطاقة شحرور - خروج مجاني من المسكوبية
}